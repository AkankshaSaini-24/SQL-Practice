-- ============================================================
-- Retail practice database (SQLite)
-- A small star schema: 3 dimensions, an order header fact and an
-- order line fact, plus a targets table and a messy raw table.
-- Run this file once on an empty database to create everything.
-- ============================================================

DROP TABLE IF EXISTS fact_order_lines;
DROP TABLE IF EXISTS fact_orders;
DROP TABLE IF EXISTS dim_customer;
DROP TABLE IF EXISTS dim_product;
DROP TABLE IF EXISTS dim_date;
DROP TABLE IF EXISTS sales_targets;
DROP TABLE IF EXISTS raw_customers;

CREATE TABLE dim_customer (
  customer_key   INTEGER PRIMARY KEY,
  customer_name  TEXT NOT NULL,
  city           TEXT,
  segment        TEXT,
  signup_date    TEXT            -- ISO date, YYYY-MM-DD
);

CREATE TABLE dim_product (
  product_key    INTEGER PRIMARY KEY,
  product_name   TEXT NOT NULL,
  category       TEXT,
  unit_price     REAL,           -- SEK
  unit_cost      REAL            -- SEK
);

CREATE TABLE dim_date (
  date_key       INTEGER PRIMARY KEY,  -- YYYYMMDD
  full_date      TEXT,                 -- ISO date
  year           INTEGER,
  quarter        INTEGER,
  month          INTEGER,
  month_name     TEXT,
  day_of_week    TEXT,
  is_weekend     INTEGER               -- 1 = Saturday/Sunday
);

CREATE TABLE fact_orders (            -- grain: one row per order
  order_id       INTEGER PRIMARY KEY,
  customer_key   INTEGER REFERENCES dim_customer(customer_key),
  order_date_key INTEGER REFERENCES dim_date(date_key),
  status         TEXT,                 -- delivered / cancelled / returned / shipped
  delivery_days  INTEGER               -- NULL for cancelled and shipped orders
);

CREATE TABLE fact_order_lines (       -- grain: one row per product on an order
  order_id       INTEGER REFERENCES fact_orders(order_id),
  line_number    INTEGER,
  product_key    INTEGER REFERENCES dim_product(product_key),
  quantity       INTEGER,
  unit_price     REAL,
  discount_pct   INTEGER,
  net_revenue    REAL,
  PRIMARY KEY (order_id, line_number)
);

CREATE TABLE sales_targets (          -- monthly revenue target per category, 2025
  category       TEXT,
  year           INTEGER,
  month          INTEGER,
  target_revenue REAL
);

CREATE TABLE raw_customers (          -- messy staging data for cleaning exercises
  customer_id    INTEGER,
  full_name      TEXT,
  email          TEXT,
  city           TEXT,
  updated_at     TEXT
);

